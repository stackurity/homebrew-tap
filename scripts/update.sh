#!/usr/bin/env bash
# Writes Formula/stackurity.rb for a Stackurity release (default: the latest),
# after verifying the release's signed checksums. Used by the update workflow.
set -euo pipefail
cd "$(dirname "$0")/.."
VERSION="${1:-}"
if [ -z "$VERSION" ]; then
  VERSION=$(curl -fsSL ${GH_TOKEN:+-H "Authorization: Bearer $GH_TOKEN"} https://api.github.com/repos/stackurity/stackurity/releases/latest \
    | sed -n 's/^ *"tag_name": *"\([^"]*\)".*/\1/p' | head -1)
fi
case "$VERSION" in v[0-9]*) ;; *) echo "bad version: $VERSION" >&2; exit 1 ;; esac
base="https://github.com/stackurity/stackurity/releases/download/$VERSION"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
curl -fsSLo "$tmp/SHA256SUMS" "$base/SHA256SUMS"
curl -fsSLo "$tmp/SHA256SUMS.sigstore.json" "$base/SHA256SUMS.sigstore.json"
cosign verify-blob --bundle "$tmp/SHA256SUMS.sigstore.json" \
  --certificate-identity "https://github.com/stackurity/stackurity/.github/workflows/release.yml@refs/tags/$VERSION" \
  --certificate-oidc-issuer https://token.actions.githubusercontent.com "$tmp/SHA256SUMS" >&2
sum() {
  local s
  s=$(awk -v f="stackurity_${VERSION}_$1" '$2 == f { print $1 }' "$tmp/SHA256SUMS")
  [ ${#s} -eq 64 ] || { echo "no checksum for $1" >&2; exit 1; }
  echo "$s"
}
cat > Formula/stackurity.rb <<RUBY
# Generated by scripts/update.sh from the signed checksums of Stackurity ${VERSION}.
class Stackurity < Formula
  desc "Software inventory, vulnerability and upgrade intelligence (CLI, agent and server)"
  homepage "https://stackurity.ai"
  version "${VERSION#v}"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "${base}/stackurity_${VERSION}_darwin_arm64"
      sha256 "$(sum darwin_arm64)"
    end
    on_intel do
      url "${base}/stackurity_${VERSION}_darwin_amd64"
      sha256 "$(sum darwin_amd64)"
    end
  end

  on_linux do
    on_arm do
      url "${base}/stackurity_${VERSION}_linux_arm64"
      sha256 "$(sum linux_arm64)"
    end
    on_intel do
      url "${base}/stackurity_${VERSION}_linux_amd64"
      sha256 "$(sum linux_amd64)"
    end
  end

  def install
    bin.install Dir["stackurity_*"].first => "stackurity"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/stackurity --version")
  end
end
RUBY
echo "$VERSION"
